/**
 * 붙여넣기·드롭 그림 한도 (04 §3.3).
 *
 * 5MB였다가 4MB로 내렸다(2026-09-05). **Vercel의 함수 본문 한도가 4.5MB이고 바꿀 수 없다** —
 * 5MB를 받는다고 적어두면 4.5~5MB 구간이 우리 문구가 아니라 플랫폼 오류로 떨어진다.
 * 한도는 우리가 먼저 걸러 사람 말로 답할 수 있는 자리에 있어야 한다.
 *
 * 이관 스크립트는 이 값을 쓰지 않는다(서버에서 직접 올린다) — 옛 글의 큰 그림은 그대로다.
 *
 * **이 파일은 순수하다.** 값이 `lib/storage/images`에 있었는데 그 모듈은 server-only라,
 * 화면에서 "4MB까지 올릴 수 있어요"를 적으려고 불러오는 순간 빌드가 깨졌다 — 한도는
 * 서버와 화면이 함께 봐야 하는 값이다.
 */
export const MAX_IMAGE_BYTES = 4 * 1024 * 1024;

/** 화면에 적을 한도 — "4MB" */
export const MAX_IMAGE_LABEL = `${Math.floor(MAX_IMAGE_BYTES / 1024 / 1024)}MB`;
