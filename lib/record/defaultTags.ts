import type { RecordType } from "@/lib/record/callNumber";

/**
 * 새 글에 미리 놓는 태그 (02 §5.2~5.4).
 *
 * 묵상 세 종류는 **거의 매번 같은 태그**가 붙는다. 매일 같은 네 개를 손으로 치는 것이
 * 기록의 문턱을 올리므로 미리 놓는다 — 지우는 것이 더하는 것보다 싸다(태그마다 ✕가 있다).
 *
 * 목록은 지어낸 것이 아니라 **이관해 온 글에서 세었다**(dev 595편, 2026-09-05):
 *
 *   QT     묵상 97% · 날마다 솟는 샘물 97% · 날솟샘 97% · QT 96%
 *   설교   예배 81% · 설교 81% · 주일 74%
 *   찬양   찬양 98% · 묵상 60% · 가사 60% · CCM 98%(`ccm` 60% + `CCM` 38%)
 *
 * **넣지 않은 것들:**
 * - 교회 이름(사랑스러운교회 59% · 유강침례교회 25%) — 옮겨 다니는 값을 코드에 박지 않는다
 * - 아티스트(어노인팅 54% · 제이어스 16%) — 곡마다 다르다
 * - `주일`은 74%라 수요채플·특별새벽기도회에는 틀리다. 그래도 넣는다: 네 번 중 세 번 맞고,
 *   틀린 날은 한 번 지우면 된다
 *
 * 기술 글에는 두지 않는다. 주제가 매번 달라 공통 태그가 없다(태그 208종 중 1~2편짜리가 대부분).
 *
 * **새 글에만 놓는다.** 저장된 글을 다시 열 때는 넣지 않는다 — 일부러 지운 태그가 되살아나면
 * 그건 고장이다.
 */
export const DEFAULT_TAGS: Partial<Record<RecordType, readonly string[]>> = {
  QT: ["QT", "묵상", "날마다 솟는 샘물", "날솟샘"],
  SERMON: ["설교", "예배", "주일"],
  PRAISE: ["찬양", "CCM", "가사", "묵상"],
};

/** 빈 폼이 들고 시작할 태그. 배열은 매번 새로 만든다 — 폼이 고쳐 쓰는 값이다 */
export function defaultTagsFor(type: RecordType): string[] {
  return [...(DEFAULT_TAGS[type] ?? [])];
}

/**
 * 사람이 태그를 손댔는가 (서식 전환 조건, 02 §2.4).
 *
 * 기본 태그는 **폼이 놓아준 것이지 사람이 쓴 것이 아니다.** QT의 질문 프리셋을 "쓴 글"로
 * 세지 않는 것과 같은 논리다 — 그것까지 세면 새 글은 열리자마자 서식이 잠긴다.
 *
 * 기본 태그 중 일부를 지운 것도 손댄 것으로 보지 않는다. 서식을 바꾸면 그 서식의 기본
 * 태그로 다시 놓이므로 잃을 것이 없다.
 */
export function hasOwnTags(type: RecordType, tags: string[]): boolean {
  const defaults = new Set(DEFAULT_TAGS[type] ?? []);
  return tags.some((tag) => !defaults.has(tag));
}
