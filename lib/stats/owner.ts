/**
 * 운영자 본인의 방문 표시 (05 §4.1).
 *
 * **처음에는 "빼달라"는 표시였다.** 이 쿠키가 있으면 비콘이 입을 닫고 서버도 받지 않았다 —
 * 그러면 내 방문은 **기록 자체가 남지 않는다.** 나중에 "본인 포함하면 몇이야"를 물을 수 없고,
 * 반대로 옵트아웃을 없애면 이번엔 영원히 섞여서 "본인 빼면 몇이야"를 물을 수 없다.
 *
 * 그래서 **버리지 않고 표시한다.** 전부 기록하고 읽을 때 고른다 — 공개 지면은 전부 세고,
 * 관리 화면은 본인 포함·제외를 나란히 본다. 수집 시점에 버린 것은 되돌릴 수 없지만, 표시해
 * 둔 것은 언제든 다시 고를 수 있다.
 *
 * **왜 쿠키 한 장인가.** 공개 지면은 통째로 캐시되고(ADR-003) 비콘도 그 캐시된 HTML에 실려
 * 나간다. 그래서 "관리자냐"를 서버가 지면에서 판단할 수 없다 — 판단하려면 공개 지면마다
 * Supabase 세션을 확인해야 하고, 그건 캐시를 버리는 것과 같다.
 *
 * 대신 관리 영역을 지날 때 **이미 알아낸 사실**을 쿠키에 적어 둔다(proxy가 `/admin`에서 세션을
 * 확인한다).
 * 그 뒤로는 비콘이 `document.cookie` 한 줄만 보고 조용히 입을 닫는다. 공개 지면에 추가 비용이
 * 0이고, 캐시를 건드리지 않는다.
 *
 * 이 쿠키에는 비밀이 없다 — 값은 `1` 하나다. 남이 이걸 심으면 자기 방문이 **운영자 것으로
 * 표시될** 뿐이고, 공개 지면은 어차피 전부 세므로 보이는 숫자는 그대로다. 관리 화면의
 * "본인 제외"만 그만큼 흐려지는데, 그건 공격이라기엔 얻는 것이 없다. 그래서 httpOnly도
 * 서명도 필요 없다(비콘이 읽어야 하므로 httpOnly면 애초에 동작하지 않는다).
 */

/**
 * 이름을 바꿨다(2026-09-06). `stat_optout`은 "빼달라"는 뜻인데 이제 "이건 나다" 표시다.
 * 바꾸는 대가는 한 번 — `/admin`에 다시 들어갈 때까지 본인 표시가 붙지 않는다.
 */
export const STAT_OWNER_COOKIE = "stat_owner";

/** 1년. 관리자가 매달 로그인을 다시 하지 않아도 표시가 유지돼야 한다 */
export const STAT_OWNER_MAX_AGE = 60 * 60 * 24 * 365;

/**
 * 3면이 서브도메인으로 갈리면(dev.○ / faith.○) 루트에서 심은 쿠키가 하위 지면에 보이지 않는다.
 * 그래서 루트 호스트가 설정돼 있으면 **부모 도메인에 심는다**. 미설정 단계에서는 3면이 한
 * 호스트를 공유하므로(Vercel 기본 주소) 호스트 한정으로 두면 된다.
 */
export function ownerCookieDomain(rootHost: string | undefined): string | undefined {
  if (!rootHost) return undefined;

  const host = rootHost.trim().toLowerCase().split(":")[0] ?? "";
  // 라벨이 둘 미만이면(localhost) 도메인 속성을 붙일 수 없다
  return host.split(".").length >= 2 ? `.${host}` : undefined;
}
